const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const app = fs.readFileSync('ui/app.js', 'utf8');
const status = {textContent:'', style:{}};
const statuses = new Map([['vorlesen','🔊 vorlesen']]);
const context = {statuses, $:()=>status};
vm.createContext(context);
vm.runInContext(app.slice(app.indexOf('function renderStatus()'), app.indexOf('function renderWidgets()')), context);
context.renderStatus();
assert.equal(status.textContent, ''); assert.equal(status.style.display, 'none');
statuses.set('other','Other extension'); context.renderStatus();
assert.equal(status.textContent,'Other extension'); assert.equal(status.style.display,'block');
assert.equal(statuses.get('vorlesen'),'🔊 vorlesen');
const html = fs.readFileSync('ui/index.html','utf8');
const controls = html.match(/<div id="sendcontrols">(.*?)<\/div>/s)[1];
for (const id of ['promptexpand','send','abort']) assert(controls.includes(`id="${id}"`));
assert(html.includes('grid-template-rows:repeat(3,1fr); gap:4px;'));
console.log('Footer: speech status hidden, other statuses preserved; three actions in one uniform column');
