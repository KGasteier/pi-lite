const assert=require('node:assert/strict');
const {createSessionBookmarks}=require('../ui/session-bookmarks.js');
const data=new Map(), storage={getItem:k=>data.get(k),setItem:(k,v)=>data.set(k,v)};
const b=createSessionBookmarks(storage), sessions=[{path:'a',modified:30},{path:'b',modified:20},{path:'c',modified:10}];
b.toggle('b');b.toggle('c');b.setColor('b',4);b.setColor('c',1);
assert.equal(b.filterMode,'off');assert.equal(b.visible(sessions).length,3);
b.cycleFilterMode();assert.equal(b.filterMode,'on');assert.deepEqual(b.sort(b.visible(sessions)).map(s=>s.path),['b','c']);
b.cycleFilterMode();assert.equal(b.filterMode,'colors');assert.deepEqual(b.sort(b.visible(sessions)).map(s=>s.path),['c','b']);
assert.equal(createSessionBookmarks(storage).filterMode,'colors');b.cycleFilterMode();assert.equal(b.filterMode,'off');
console.log('Bookmark-Modi: Zeit, Bookmark-Zeit und Kategorie/Zeit geprüft.');
