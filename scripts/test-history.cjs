const assert = require('node:assert/strict');
const History = require('../ui/history.js');
const h = new History();
assert.equal(h.move(-1, 'draft'), 'draft');
const msg = (role, content) => ({type:'message', message:{role, content}});
h.replace(History.entries([msg('user','one'),{type:'compaction',summary:'nicht als Prompt'},msg('toolResult','kein Prompt'),msg('user',[{type:'image',data:'xyz'},{type:'text',text:'two'}]),msg('user','two')]));
assert.deepEqual(h.items, ['one', 'two', 'two']);
assert.equal(h.move(-1, 'draft'), 'two');
assert.equal(h.move(-1, 'two'), 'two');
assert.equal(h.move(-1, 'two'), 'one');
assert.equal(h.move(-1, 'one'), 'one');
assert.equal(h.move(3, 'one'), 'draft');
h.replace(Array.from({length:300},(_,i)=>'Prompt '+i));
assert.equal(h.move(-300, 'draft'), 'Prompt 0');
assert.equal(h.move(300, 'Prompt 0'), 'draft');
h.replace(['other session']);
assert.equal(h.move(-1, 'new draft'), 'other session');
console.log('Session-Prompthistorie: alle Prompts, Wiederholungen, Entwurf und Sessionwechsel grün');
