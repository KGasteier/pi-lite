const fs = require('node:fs'), assert = require('node:assert/strict');
const html = fs.readFileSync('ui/index.html','utf8');
const head = html.slice(html.indexOf('<div id="sidehead">'), html.indexOf('<div id="sessions">'));
assert(head.indexOf('id="sideview"') < head.indexOf('id="sidetools"'));
for (const id of ['sideview','sidetools','newsess','sessionsort','bookmarkfilter','sidehint']) assert(head.includes(`id="${id}"`));
assert(!head.includes('<h3>')); assert(!head.includes('cacheclear'));
const preview = html.slice(html.indexOf('<div id="preview"'), html.indexOf('\n', html.indexOf('<div id="preview"')));
assert(preview.includes('id="cacheclear"') && preview.includes('Gespeicherte Kurzinfos löschen'));
assert(html.includes('appearance:none') && html.includes('select:hover, select:focus-visible'));
assert(html.includes('<div id="logwrap"><div id="log"') && html.includes('#logwrap:has(#log:focus-visible)::after'));
const st = html.match(/<span id="status"[^>]*>(.*?)<\/span><\/span>/s); assert(st && (st[1].match(/<i><\/i>/g)||[]).length === 8 && st[0].includes('id="statustext"'));
assert(html.includes('@keyframes pixelsnake') && html.includes('prefers-reduced-motion'));
const app = fs.readFileSync('ui/app.js','utf8');
assert(app.includes('statusEl.classList.toggle("busy", busy)') && !app.includes('"🗑"') && app.includes('"delete", "Session löschen"'));
const group = html.slice(html.indexOf('<div id="workspacegroup"'),html.indexOf('<div class="picker" id="modelpicker"'));
assert(group.includes('id="cwdpicker"')); assert(group.includes('id="workspaceeditor"'));
assert(group.includes('aria-label="Workspace in VSCodium öffnen"'));
assert(!group.includes('↗ Editor'));
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length,'No duplicate element IDs');
console.log('Sidebar/header structure: compact common toolbar and grouped icon editor passed; bookmark filter, preview cache link, pixel spinner, flat selects, log focus overlay structure; no live layout test.');
