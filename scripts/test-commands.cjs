const assert = require('node:assert/strict');
const { parseInput, isNewerVersion, LOCAL_COMMANDS } = require('../ui/commands.js');
assert.deepEqual(parseInput('pi update'), { kind: 'cli', args: ['update'] });
assert.deepEqual(parseInput('  pi update --extensions '), { kind: 'cli', args: ['update', '--extensions'] });
assert.deepEqual(parseInput('pi --version'), { kind: 'cli', args: ['--version'] });
assert.equal(parseInput('pi ist ein Agent').kind, 'prompt');
assert.equal(parseInput('Was macht pi update?').kind, 'prompt');
assert.equal(parseInput('pi config').kind, 'prompt');
assert.equal(parseInput('pi').kind, 'prompt');
assert.deepEqual(parseInput('!ls -la'), { kind: 'bash', command: 'ls -la', exclude: false });
assert.deepEqual(parseInput('!!git status'), { kind: 'bash', command: 'git status', exclude: true });
assert.equal(parseInput('!').kind, 'prompt');
assert.deepEqual(parseInput('/thinking high'), { kind: 'local', name: 'thinking', arg: 'high' });
assert.deepEqual(parseInput('/model'), { kind: 'local', name: 'model', arg: '' });
assert.equal(parseInput('/settings').kind, 'terminal');
assert.equal(parseInput('/implement foo').kind, 'prompt');
assert.equal(parseInput('/skill:meshdev').kind, 'prompt');
assert.ok(LOCAL_COMMANDS.every(c => c.source === 'local'));
assert.ok(isNewerVersion('1.1.0', '1.0.4') && !isNewerVersion('1.0.4', '1.0.4') && !isNewerVersion('1.0.3', '1.0.4') && isNewerVersion('1.0.10', '1.0.9') && isNewerVersion('2.0.0', '1.9.9'));
console.log('Commands: pi-CLI, Shell, lokale Slash-Befehle, Versionsvergleich passed');
